def label(text, name='muted'):
    item = QLabel(text)
    item.setTextFormat(Qt.TextFormat.PlainText)
    item.setObjectName(name)
    return item


def button(text, callback, name='', symbol=None):
    item = QPushButton(text)
    item.setObjectName(name)
    item.setAccessibleName(text)
    item.clicked.connect(callback)
    if symbol:
        item.setProperty('iconName', symbol)
        item.setIcon(icon(symbol))
        item.setIconSize(QSize(18,18))
    return item


def row_layout(widget=None, margins=(0,0,0,0), spacing=8):
    row = QHBoxLayout(widget)
    row.setContentsMargins(*margins)
    row.setSpacing(spacing)
    return row


def column(widget=None, margins=(0,0,0,0), spacing=12):
    layout = QVBoxLayout(widget)
    layout.setContentsMargins(*margins)
    layout.setSpacing(spacing)
    return layout


def separator():
    item = QFrame()
    item.setObjectName('separator')
    return item


def scrollable(widget):
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    scroll.setWidget(widget)
    return scroll


class ChoiceCard(QPushButton):
    def __init__(self, title, description, parent=None, *, preview=None):
        super().__init__(parent)
        self.setObjectName('choiceCard')
        self.setCheckable(True)
        self.setAccessibleName(title)
        self.setToolTip(description)
        self.setMinimumHeight(66)
        self.setSizePolicy(QSizePolicy.Policy.Expanding,QSizePolicy.Policy.Fixed)
        layout = row_layout(self, (14,10,12,10), 10)
        self.indicator = QRadioButton()
        self.indicator.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
        self.indicator.setFocusPolicy(Qt.FocusPolicy.NoFocus)
        layout.addWidget(self.indicator)
        texts = column(spacing=4)
        heading = label(title, 'paneTitle')
        note = label(description, 'caption')
        note.setWordWrap(True)
        for item in (heading, note):
            item.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
            texts.addWidget(item)
        layout.addLayout(texts, 1)
        if preview:
            from .layout_preview import LayoutPreview
            layout.addWidget(LayoutPreview(preview))
        self.toggled.connect(self.indicator.setChecked)


